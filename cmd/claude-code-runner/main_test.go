const (
	peerTool  = "ask-web-agent"
	peerAddr  = "http://web-agent-peer.default.svc:8080"
	skillName = "refunds"
)

func testConfig() *sdk.AgentConfig {
	return &sdk.AgentConfig{
		Namespace: "default",
		Name:      "api-agent",
		Phase:     sdk.PhaseReady,
		Prompt:    &sdk.Prompt{System: "You own the API repository."},
		Skills: []sdk.Skill{
			{Name: skillName, Description: "How to process a refund", Content: "STEP 1 …",
				AllowedTools: []string{"refund"}},
			{Name: "empty", Content: ""}, // no body: must be skipped
		},
		Tools: []sdk.Tool{
			{Name: peerTool, Type: toolTypeMCP, Endpoint: peerAddr, Description: "Owns the web frontend"},
			{Name: "plain-http", Type: "http", Endpoint: "http://svc/tool"},
		},
	}
}

// The whole design rests on projection: Claude Code takes no injected prompt, so
// the Agent's prompt and Skills have to arrive as the file it already reads.
func TestBuildInstructions(t *testing.T) {
	got := buildInstructions(testConfig())

	for _, want := range []string{
		"You own the API repository.",
		"# Skill: " + skillName,
		"STEP 1 …",
		"restrict yourself to these tools: refund",
		"# Other repositories",
		peerTool,
		"Owns the web frontend",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("CLAUDE.md missing %q:\n%s", want, got)
		}
	}
	// A Skill with no body would render an empty heading.
	if strings.Contains(got, "# Skill: empty") {
		t.Errorf("content-less skill was rendered:\n%s", got)
	}
	// The file is regenerated on every config change, so say so in it.
	if !strings.HasPrefix(got, "<!-- Generated by agent-plane") {
		t.Error("CLAUDE.md lacks the generated-file marker")
	}
}

// An Agent with neither prompt nor skills must still produce a valid file
// rather than a stray heading or a panic.
func TestBuildInstructionsEmpty(t *testing.T) {
	got := buildInstructions(&sdk.AgentConfig{})
	if strings.Contains(got, "# Skill:") || strings.Contains(got, "# Other repositories") {
		t.Errorf("empty config produced section headings:\n%s", got)
	}
}

func TestBuildMCPConfig(t *testing.T) {
	raw, err := buildMCPConfig(testConfig())
	if err != nil {
		t.Fatalf("buildMCPConfig: %v", err)
	}
	var doc struct {
		MCPServers map[string]mcpServerEntry `json:"mcpServers"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("output is not valid JSON: %v\n%s", err, raw)
	}

	entry, ok := doc.MCPServers[peerTool]
	if !ok {
		t.Fatalf("mcp tool missing from .mcp.json: %s", raw)
	}
	if entry.URL != peerAddr {
		t.Errorf("URL = %q, want the resolved endpoint", entry.URL)
	}
	// An http Tool has no MCP representation. Emitting one anyway would advertise
	// a server the CLI cannot reach, which fails at call time instead of never
	// appearing.
	if _, leaked := doc.MCPServers["plain-http"]; leaked {
		t.Error("an http tool was written into .mcp.json")
	}
}

// An mcp Tool whose endpoint has not resolved yet must not become an entry
// pointing nowhere.
func TestBuildMCPConfigSkipsUnresolvedEndpoints(t *testing.T) {
	cfg := &sdk.AgentConfig{Tools: []sdk.Tool{{Name: "not-ready", Type: toolTypeMCP}}}
	raw, err := buildMCPConfig(cfg)
	if err != nil {
		t.Fatalf("buildMCPConfig: %v", err)
	}
	if strings.Contains(string(raw), "not-ready") {
		t.Errorf("unresolved tool was written into .mcp.json:\n%s", raw)
	}
}

func TestProjectWritesBothFiles(t *testing.T) {
	dir := t.TempDir()
	r := &runner{cfg: testConfig(), workspace: dir}
	if err := r.project(); err != nil {
		t.Fatalf("project: %v", err)
	}
	for _, f := range []string{"CLAUDE.md", ".mcp.json"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err != nil {
			t.Errorf("%s not written: %v", f, err)
		}
	}
}

// Re-projection overwrites rather than appending — a hot reload must not leave
// the previous config's instructions behind.
func TestProjectIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	r := &runner{cfg: testConfig(), workspace: dir}
	if err := r.project(); err != nil {
		t.Fatalf("project: %v", err)
	}
	first, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))

	for range 3 {
		if err := r.project(); err != nil {
			t.Fatalf("re-project: %v", err)
		}
	}
	after, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if string(after) != string(first) {
		t.Error("re-projection changed the file; it should overwrite identically")
	}
}

func TestToolPermissions(t *testing.T) {
	cfg := testConfig()
	cfg.Policy = &sdk.Policy{
		Tools: &sdk.AccessRule{Deny: []string{peerTool}},
	}
	allowed, disallowed, _ := toolPermissions(cfg, policy.New(cfg.Policy))

	if len(allowed) != 0 {
		t.Errorf("allowed = %v, want none", allowed)
	}
	// Claude Code names MCP tools mcp__<server>; a bare tool name would not match.
	if len(disallowed) != 1 || disallowed[0] != "mcp__"+peerTool {
		t.Errorf("disallowed = %v, want [mcp__%s]", disallowed, peerTool)
	}
}

// With no Policy the runner must pass no permission flags at all, rather than
// an empty allowlist — which the CLI would read as "allow nothing".
func TestToolPermissionsWithoutPolicy(t *testing.T) {
	allowed, disallowed, unenforced := toolPermissions(testConfig(), policy.New(nil))
	if allowed != nil || disallowed != nil || unenforced != nil {
		t.Errorf("got (%v, %v, %v), want all nil", allowed, disallowed, unenforced)
	}
}

// The honesty requirement: policy this runtime cannot enforce must be reported,
// not silently dropped. A ToolPolicy that looks applied while half of it is
// inert is worse than one that says what it cannot do.
func TestToolPermissionsReportsWhatItCannotEnforce(t *testing.T) {
	cap2 := int32(2)
	cfg := testConfig()
	cfg.Policy = &sdk.Policy{
		ToolRules: []sdk.ToolRule{
			{Tool: peerTool, Action: sdk.ToolActionAllow, MaxCallsPerSession: &cap2},
		},
		DefaultToolAction: sdk.ToolActionDeny,
	}
	_, _, unenforced := toolPermissions(cfg, policy.New(cfg.Policy))

	joined := strings.Join(unenforced, "\n")
	if !strings.Contains(joined, "maxCallsPerSession") {
		t.Errorf("call caps not reported as unenforced:\n%s", joined)
	}
	// The built-in tools are the real gap: ToolPolicy names Tool CRs, and Bash is
	// not one.
	if !strings.Contains(joined, "built-in") {
		t.Errorf("built-in tool gap not reported:\n%s", joined)
	}
}

// stubCLI writes a fake `claude` that emits the JSON envelope the runner parses,
// so the HTTP surface can be exercised without the real CLI.
func stubCLI(t *testing.T, body string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "claude-stub")
	script := "#!/bin/sh\ncat <<'JSON'\n" + body + "\nJSON\n"
	if err := os.WriteFile(path, []byte(script), 0o755); err != nil {
		t.Fatalf("write stub: %v", err)
	}
	return path
}

func TestHandleChat(t *testing.T) {
	r := &runner{
		cfg:       testConfig(),
		enforcer:  policy.New(nil),
		workspace: t.TempDir(),
		cli:       stubCLI(t, `{"result":"done","session_id":"sess-1","is_error":false}`),
		env:       os.Environ(),
		timeout:   time.Minute,
		sessions:  map[string]string{},
	}

	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodPost, "/api/chat",
		strings.NewReader(`{"sessionId":"chat-42","message":"fix the bug"}`))
	r.handleChat(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", rec.Code)
	}
	var out map[string]string
	if err := json.NewDecoder(rec.Body).Decode(&out); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if out["answer"] != "done" {
		t.Errorf("answer = %q, want %q", out["answer"], "done")
	}
	// The caller's session id must map to the CLI's, so the next turn resumes the
	// same conversation rather than starting cold.
	if r.sessions["chat-42"] != "sess-1" {
		t.Errorf("session map = %v, want chat-42 -> sess-1", r.sessions)
	}
}

// A CLI-reported failure is returned in the body with HTTP 200: the adapter
// contract treats a non-200 as a transport error, so surfacing it that way would
// make a model-level failure look like the runner is down.
func TestHandleChatCLIError(t *testing.T) {
	r := &runner{
		cfg:       testConfig(),
		enforcer:  policy.New(nil),
		workspace: t.TempDir(),
		cli:       stubCLI(t, `{"result":"context exhausted","is_error":true}`),
		env:       os.Environ(),
		timeout:   time.Minute,
		sessions:  map[string]string{},
	}

	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodPost, "/api/chat",
		strings.NewReader(`{"message":"hi"}`))
	r.handleChat(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 with an error body", rec.Code)
	}
	var out map[string]string
	_ = json.NewDecoder(rec.Body).Decode(&out)
	if !strings.Contains(out["error"], "context exhausted") {
		t.Errorf("error = %q, want the CLI's message", out["error"])
	}
}

func TestHandleChatRejectsBadRequests(t *testing.T) {
	r := &runner{cfg: testConfig(), enforcer: policy.New(nil), sessions: map[string]string{}}

	rec := httptest.NewRecorder()
	r.handleChat(rec, httptest.NewRequest(http.MethodGet, "/api/chat", nil))
	if rec.Code != http.StatusMethodNotAllowed {
		t.Errorf("GET status = %d, want 405", rec.Code)
	}

	rec = httptest.NewRecorder()
	r.handleChat(rec, httptest.NewRequest(http.MethodPost, "/api/chat", strings.NewReader(`{}`)))
	if rec.Code != http.StatusBadRequest {
		t.Errorf("empty message status = %d, want 400", rec.Code)
	}
}

// Claude Code edits the one working tree this pod owns, so turns must not
// overlap. The Operator pins the Deployment to a single replica for the same
// reason; this is the in-process half.
func TestTurnsAreSerialized(t *testing.T) {
	r := &runner{
		cfg:       testConfig(),
		enforcer:  policy.New(nil),
		workspace: t.TempDir(),
		cli:       stubCLI(t, `{"result":"ok","session_id":"s","is_error":false}`),
		env:       os.Environ(),
		timeout:   time.Minute,
		sessions:  map[string]string{},
	}

	var wg sync.WaitGroup
	for i := range 8 {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			if _, err := r.turn(context.Background(), "s", "msg"); err != nil {
				t.Errorf("turn %d: %v", i, err)
			}
		}(i)
	}
	wg.Wait() // the race detector fails this if the lock is missing
}
